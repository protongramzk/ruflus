export const getLocale = (lang?: string): string => {
  switch (lang) {
    case 'ms': return 'ms-MY';
    case 'ja': return 'ja-JP';
    case 'zh': return 'zh-CN';
    case 'id':
    default:
      return 'id-ID';
  }
};

export const t = (key: string, lang?: string): string => {
  const language = lang || 'id';
  const translationsMap = (translations as any)[language];
  if (translationsMap && translationsMap[key] !== undefined) {
    return translationsMap[key];
  }
  // Fallback to id
  const fallbackMap = (translations as any)['id'];
  if (fallbackMap && fallbackMap[key] !== undefined) {
    return fallbackMap[key];
  }
  return key;
};

export const translateCategory = (catId: string, defaultName: string, lang?: string): string => {
  const language = lang || 'id';
  const keys: Record<string, string> = {
    'cat-in-gaji': 'gaji',
    'cat-in-bonus': 'bonus',
    'cat-in-investasi': 'investasi',
    'cat-in-lain': 'lain',
    'cat-ex-makan': 'makan',
    'cat-ex-transport': 'transport',
    'cat-ex-belanja': 'belanja',
    'cat-ex-hiburan': 'hiburan',
    'cat-ex-tagihan': 'tagihan',
    'cat-ex-lain': 'lain',
  };
  const key = keys[catId];
  if (key && (translations as any)[language]?.[key]) {
    return (translations as any)[language][key];
  }
  return defaultName;
};

export const formatAmount = (amount: number, currency: string, lang?: string): string => {
  const locale = getLocale(lang);
  // Japan and China currencies do not normally use decimals (especially Yen)
  const isZeroDecimal = currency === '¥';
  const formatted = amount.toLocaleString(locale, {
    minimumFractionDigits: isZeroDecimal ? 0 : 0,
    maximumFractionDigits: isZeroDecimal ? 0 : 2
  });
  return `${currency} ${formatted}`;
};
